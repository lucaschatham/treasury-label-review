import assert from 'node:assert/strict';
import {inferAppearance} from '../../worker/vision.js';
import {appearanceFinding} from '../../src/appearance.js';
const success=await inferAppearance({run:async()=>({choices:[{message:{content:'BOLD'}}]})},'fixture',50);
